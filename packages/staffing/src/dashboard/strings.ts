export type StringKey = keyof typeof en;
export const t = makeT<StringKey>();

/** `t` with each `{name}` in the text replaced by its value. */
export function tf(key: StringKey, values: Record<string, string>, locale?: string): string {
  return t(key, locale).replace(/\{(\w+)\}/g, (whole, name: string) => values[name] ?? whole);
}

/** "No people"; the names; or the first `shown` names "plus N more". */
export function holderNames(names: readonly string[], shown: number, locale?: string): string {
  if (names.length === 0) return t("staffing.role.holders_none", locale);
  const listed = names.slice(0, shown).join(", ");
  if (names.length <= shown) return listed;
  return tf(
    "staffing.role.holders_more",
    { names: listed, count: String(names.length - shown) },
    locale,
  );
}

/** How many people a staffing block needs, in words. */
export function peopleNeeded(count: number, locale?: string): string {
  if (count === 1) return t("staffing.grid.people_one", locale);
  return tf("staffing.grid.people_other", { count: String(count) }, locale);
}

/** A rota count in words: "1 over", "3 partly uncovered". */
export function countWords(
  kind: "unfilled" | "partly" | "over",
  count: number,
  locale?: string,
): string {
  if (kind !== "unfilled" && count === 1) return t(`staffing.rota.${kind}_one`, locale);
  return tf(`staffing.rota.${kind}_count`, { count: String(count) }, locale);
}

