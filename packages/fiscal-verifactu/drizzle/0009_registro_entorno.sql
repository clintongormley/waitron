-- Which environment this registro was GENERATED for, so `drain` can refuse to submit it to the
-- other one. Immutable, like every other column here: it is a fact about the record, not about the
-- attempt to send it — which is why it lives on registros_facturacion and not on the mutable
-- `envios` sidecar.
--
-- NULLABLE with no backfill, deliberately. Rows written before this migration have no recorded
-- destination and we cannot infer one; `drain` refuses them with `fiscal.environment_unknown`
-- rather than guessing. No production deployment exists, so the only affected rows are in
-- development and throwaway databases.
--
-- NOT part of the huella. `entorno` is ours, never AEAT's: it is absent from the RegistroAlta the
-- serializer builds, and verify.test.ts pins that two records differing only here hash identically.
--
-- Generated by plain `drizzle-kit generate` (not --custom) against ./src/schema/registros.ts's own
-- `entorno` column + `registros_entorno_ck` check — unlike this package's hand-written migrations
-- (0001, 0003, 0004, 0006, 0008), this one needs no privilege/trigger/policy DDL drizzle-kit cannot
-- express, so letting it diff keeps drizzle/meta/0009_snapshot.json an accurate record of this
-- table's shape. That matters here specifically: a --custom migration on an ALREADY-tracked table
-- (as opposed to 0002/0004's brand-new tables) would leave the snapshot silently missing this
-- column while schema/registros.ts gained it, and the next plain `generate` would then propose
-- ADD COLUMN "entorno" a second time. See this task's own report for the check that ruled this out.
ALTER TABLE "registros_facturacion" ADD COLUMN "entorno" text;--> statement-breakpoint
ALTER TABLE "registros_facturacion" ADD CONSTRAINT "registros_entorno_ck" CHECK ("registros_facturacion"."entorno" is null or "registros_facturacion"."entorno" in ('production', 'preproduction'));
