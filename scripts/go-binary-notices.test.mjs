import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { afterEach, describe, expect, it } from "vitest";
import { generate, main, renderNotices } from "./go-binary-notices.mjs";
import { renderNotices as renderLitestreamNotices } from "./litestream-notices.mjs";

const scratch = [];
afterEach(() => {
  for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true });
});
const tempDir = () => {
  const dir = mkdtempSync(join(tmpdir(), "go-binary-notices-test-"));
  scratch.push(dir);
  return dir;
};

/** @param {Record<string, string>} files */
function makeZip(files) {
  const dir = tempDir();
  for (const [path, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, "in", path)), { recursive: true });
    writeFileSync(join(dir, "in", path), contents);
  }
  const out = join(dir, "out.zip");
  execFileSync("zip", ["-q", "-r", "-X", out, "."], { cwd: join(dir, "in") });
  return readFileSync(out);
}

const PROXY = "https://proxy.golang.org";
const APACHE = "Apache License\nVersion 2.0, January 2004\n";
const BSD = "Copyright (c) 2009 The Go Authors. All rights reserved.\n";

const buildinfo = (main = "v1.8.0") =>
  [
    "/w/bin-x86_64: go1.27.1",
    "\tpath\tgithub.com/versity/versitygw/cmd/versitygw",
    `\tmod\tgithub.com/versity/versitygw\t${main}\t`,
    "\tbuild\tGOARCH=amd64",
    "\tbuild\tGOOS=linux",
    "",
  ].join("\n");

function fakeFetch() {
  const zips = {
    [`${PROXY}/github.com/versity/versitygw/@v/v1.8.0.zip`]: makeZip({
      "github.com/versity/versitygw@v1.8.0/LICENSE": APACHE,
    }),
    [`${PROXY}/golang.org/toolchain/@v/v0.0.1-go1.27.1.linux-amd64.zip`]: makeZip({
      "golang.org/toolchain@v0.0.1-go1.27.1.linux-amd64/LICENSE": BSD,
    }),
  };
  return async (url) =>
    zips[url] === undefined
      ? { ok: false, status: 404, statusText: "Not Found", arrayBuffer: async () => null }
      : { ok: true, status: 200, statusText: "OK", arrayBuffer: async () => zips[url] };
}

describe("renderNotices", () => {
  it("writes the program's own name in the header", () => {
    const text = renderNotices({
      name: "versitygw",
      version: "1.8.0",
      command: "node scripts/go-binary-notices.mjs versitygw 1.8.0 <out> <go version -m output>...",
      go: "go1.27.1",
      platforms: ["linux/amd64", "linux/arm64"],
      modules: [],
    });
    expect(text.split("\n").slice(0, 4)).toEqual([
      "Third-party notices for versitygw, the program at /usr/local/bin/versitygw in the Waitron box image",
      "versitygw version: 1.8.0",
      "Built with: go1.27.1",
      "Generated by: node scripts/go-binary-notices.mjs versitygw 1.8.0 <out> <go version -m output>...",
    ]);
    expect(text).toContain("versitygw is a single statically linked Go program");
    expect(text).toContain("the pinned versitygw release binaries for");
    expect(text).toContain("versitygw's own licence is included as its module's LICENSE file.");
    expect(text).not.toContain("Litestream");
  });

  // The committed notice was written before the generator took a program's name; everything above
  // its module list is fixed text, so a change to the shared template shows here.
  it("writes Litestream's notice unchanged", () => {
    const committed = readFileSync("deploy/third-party/litestream/NOTICES.txt", "utf8");
    const head = committed.slice(0, committed.indexOf("Modules ("));
    const rendered = renderLitestreamNotices({
      litestream: committed.match(/^Litestream version: (\S+)$/m)?.[1],
      go: committed.match(/^Built with: (\S+)$/m)?.[1],
      platforms: ["linux/amd64", "linux/arm64"],
      modules: [],
    });
    expect(head.length).toBeGreaterThan(0);
    expect(rendered.slice(0, rendered.indexOf("Modules ("))).toBe(head);
  });
});

describe("generate", () => {
  it("refuses a version that is not the main module's", async () => {
    await expect(
      generate({
        name: "versitygw",
        version: "1.9.0",
        buildinfos: [buildinfo()],
        fetch: fakeFetch(),
      }),
    ).rejects.toThrow(/versitygw 1\.9\.0 was asked for, but the binaries are of v1\.8\.0/);
  });
});

describe("main", () => {
  const USAGE =
    "usage: node scripts/go-binary-notices.mjs <name> <version> <out> <go version -m output>...";

  const run = async (argv) => {
    const out = [];
    const err = [];
    const code = await main(argv, {
      fetch: fakeFetch(),
      stdout: (line) => out.push(line),
      stderr: (line) => err.push(line),
    });
    return { code, out, err };
  };

  it.each([
    ["no arguments", []],
    ["a name, a version and an output path but no input", ["versitygw", "1.8.0", "out.txt"]],
  ])("exits 2 with the usage line given %s", async (_, argv) => {
    expect(await run(argv)).toEqual({ code: 2, out: [], err: [USAGE] });
  });

  it("writes the named program's notices, with the command that made them", async () => {
    const dir = tempDir();
    const input = join(dir, "amd64.txt");
    writeFileSync(input, buildinfo());
    const out = join(dir, "nested", "NOTICES.txt");

    expect(await run(["versitygw", "1.8.0", out, input])).toEqual({
      code: 0,
      out: [`wrote ${out}`],
      err: [],
    });
    const text = readFileSync(out, "utf8");
    expect(text.split("\n").slice(0, 4)).toEqual([
      "Third-party notices for versitygw, the program at /usr/local/bin/versitygw in the Waitron box image",
      "versitygw version: 1.8.0",
      "Built with: go1.27.1",
      "Generated by: node scripts/go-binary-notices.mjs versitygw 1.8.0 <out> <go version -m output>...",
    ]);
    expect(text).toContain(`github.com/versity/versitygw@v1.8.0/LICENSE\n\n${APACHE}`);
  });
});
